`timescale 1ns/1ps

module decode_stage_cover (

    input logic        clk,
    input logic        rst_n,

    input logic [31:0] instr,

    input logic [4:0]  rs1_addr,
    input logic [4:0]  rs2_addr,

    input logic        pc_write,
    input logic        if_id_write,
    input logic        ctrl_mux_sel,

    input logic        reg_write,
    input logic        mem_read,
    input logic        mem_write,
    input logic        branch,
    input logic        jump,

    input logic        ex_mem_read,
    input logic [4:0]  ex_rd_addr,
    input logic        m_unit_busy
);

//////////////////////////////////////////////////////////////
// Normal Decode
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    pc_write &&
    if_id_write &&
    !ctrl_mux_sel
);

//////////////////////////////////////////////////////////////
// Load-use Hazard
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    ex_mem_read &&
    (ex_rd_addr != 5'd0) &&
    ((ex_rd_addr == rs1_addr) ||
     (ex_rd_addr == rs2_addr))
);

//////////////////////////////////////////////////////////////
// M Extension Stall
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    m_unit_busy
);

//////////////////////////////////////////////////////////////
// Register Write
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    reg_write
);

//////////////////////////////////////////////////////////////
// Memory Read
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    mem_read
);

//////////////////////////////////////////////////////////////
// Memory Write
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    mem_write
);

//////////////////////////////////////////////////////////////
// Branch Instruction
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    branch
);

//////////////////////////////////////////////////////////////
// Jump Instruction
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    jump
);

//////////////////////////////////////////////////////////////
// Pipeline Stall
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    ctrl_mux_sel
);

//////////////////////////////////////////////////////////////
// Hazard Free Decode
//////////////////////////////////////////////////////////////

cover property (
    @(posedge clk)
    rst_n &&
    !m_unit_busy &&
    !ctrl_mux_sel
);

endmodule
