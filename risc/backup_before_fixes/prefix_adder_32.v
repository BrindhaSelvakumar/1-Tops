module prefix_adder_32 (
    input  [31:0] a,
    input  [31:0] b,
    input         cin,
    output [31:0] sum,
    output        cout
);

    /*==========================================================
     * Bit Generate and Propagate
     *==========================================================*/

    wire [31:0] p;
    wire [31:0] g;

    assign p = a ^ b;
    assign g = a & b;


    /*==========================================================
     * 8 x 4-bit CLA blocks
     *
     * block 0 : bits  3:0
     * block 1 : bits  7:4
     * block 2 : bits 11:8
     * block 3 : bits 15:12
     * block 4 : bits 19:16
     * block 5 : bits 23:20
     * block 6 : bits 27:24
     * block 7 : bits 31:28
     *==========================================================*/

    wire [32:0] c;

    /* Block carry inputs */
    assign c[0] = cin;


    /*==========================================================
     * Block 0 : Bits 3:0
     *==========================================================*/

    assign c[1] =
        g[0] |
        (p[0] & c[0]);

    assign c[2] =
        g[1] |
        (p[1] & g[0]) |
        (p[1] & p[0] & c[0]);

    assign c[3] =
        g[2] |
        (p[2] & g[1]) |
        (p[2] & p[1] & g[0]) |
        (p[2] & p[1] & p[0] & c[0]);

    assign c[4] =
        g[3] |
        (p[3] & g[2]) |
        (p[3] & p[2] & g[1]) |
        (p[3] & p[2] & p[1] & g[0]) |
        (p[3] & p[2] & p[1] & p[0] & c[0]);


    /*==========================================================
     * Block 1 : Bits 7:4
     *==========================================================*/

    assign c[5] =
        g[4] |
        (p[4] & c[4]);

    assign c[6] =
        g[5] |
        (p[5] & g[4]) |
        (p[5] & p[4] & c[4]);

    assign c[7] =
        g[6] |
        (p[6] & g[5]) |
        (p[6] & p[5] & g[4]) |
        (p[6] & p[5] & p[4] & c[4]);

    assign c[8] =
        g[7] |
        (p[7] & g[6]) |
        (p[7] & p[6] & g[5]) |
        (p[7] & p[6] & p[5] & g[4]) |
        (p[7] & p[6] & p[5] & p[4] & c[4]);


    /*==========================================================
     * Block 2 : Bits 11:8
     *==========================================================*/

    assign c[9] =
        g[8] |
        (p[8] & c[8]);

    assign c[10] =
        g[9] |
        (p[9] & g[8]) |
        (p[9] & p[8] & c[8]);

    assign c[11] =
        g[10] |
        (p[10] & g[9]) |
        (p[10] & p[9] & g[8]) |
        (p[10] & p[9] & p[8] & c[8]);

    assign c[12] =
        g[11] |
        (p[11] & g[10]) |
        (p[11] & p[10] & g[9]) |
        (p[11] & p[10] & p[9] & g[8]) |
        (p[11] & p[10] & p[9] & p[8] & c[8]);


    /*==========================================================
     * Block 3 : Bits 15:12
     *==========================================================*/

    assign c[13] =
        g[12] |
        (p[12] & c[12]);

    assign c[14] =
        g[13] |
        (p[13] & g[12]) |
        (p[13] & p[12] & c[12]);

    assign c[15] =
        g[14] |
        (p[14] & g[13]) |
        (p[14] & p[13] & g[12]) |
        (p[14] & p[13] & p[12] & c[12]);

    assign c[16] =
        g[15] |
        (p[15] & g[14]) |
        (p[15] & p[14] & g[13]) |
        (p[15] & p[14] & p[13] & g[12]) |
        (p[15] & p[14] & p[13] & p[12] & c[12]);


    /*==========================================================
     * Block 4 : Bits 19:16
     *==========================================================*/

    assign c[17] =
        g[16] |
        (p[16] & c[16]);

    assign c[18] =
        g[17] |
        (p[17] & g[16]) |
        (p[17] & p[16] & c[16]);

    assign c[19] =
        g[18] |
        (p[18] & g[17]) |
        (p[18] & p[17] & g[16]) |
        (p[18] & p[17] & p[16] & c[16]);

    assign c[20] =
        g[19] |
        (p[19] & g[18]) |
        (p[19] & p[18] & g[17]) |
        (p[19] & p[18] & p[17] & g[16]) |
        (p[19] & p[18] & p[17] & p[16] & c[16]);


    /*==========================================================
     * Block 5 : Bits 23:20
     *==========================================================*/

    assign c[21] =
        g[20] |
        (p[20] & c[20]);

    assign c[22] =
        g[21] |
        (p[21] & g[20]) |
        (p[21] & p[20] & c[20]);

    assign c[23] =
        g[22] |
        (p[22] & g[21]) |
        (p[22] & p[21] & g[20]) |
        (p[22] & p[21] & p[20] & c[20]);

    assign c[24] =
        g[23] |
        (p[23] & g[22]) |
        (p[23] & p[22] & g[21]) |
        (p[23] & p[22] & p[21] & g[20]) |
        (p[23] & p[22] & p[21] & p[20] & c[20]);


    /*==========================================================
     * Block 6 : Bits 27:24
     *==========================================================*/

    assign c[25] =
        g[24] |
        (p[24] & c[24]);

    assign c[26] =
        g[25] |
        (p[25] & g[24]) |
        (p[25] & p[24] & c[24]);

    assign c[27] =
        g[26] |
        (p[26] & g[25]) |
        (p[26] & p[25] & g[24]) |
        (p[26] & p[25] & p[24] & c[24]);

    assign c[28] =
        g[27] |
        (p[27] & g[26]) |
        (p[27] & p[26] & g[25]) |
        (p[27] & p[26] & p[25] & g[24]) |
        (p[27] & p[26] & p[25] & p[24] & c[24]);


    /*==========================================================
     * Block 7 : Bits 31:28
     *==========================================================*/

    assign c[29] =
        g[28] |
        (p[28] & c[28]);

    assign c[30] =
        g[29] |
        (p[29] & g[28]) |
        (p[29] & p[28] & c[28]);

    assign c[31] =
        g[30] |
        (p[30] & g[29]) |
        (p[30] & p[29] & g[28]) |
        (p[30] & p[29] & p[28] & c[28]);

    assign c[32] =
        g[31] |
        (p[31] & g[30]) |
        (p[31] & p[30] & g[29]) |
        (p[31] & p[30] & p[29] & g[28]) |
        (p[31] & p[30] & p[29] & p[28] & c[28]);


    /*==========================================================
     * Sum
     *==========================================================*/

    assign sum[0]  = p[0]  ^ c[0];
    assign sum[1]  = p[1]  ^ c[1];
    assign sum[2]  = p[2]  ^ c[2];
    assign sum[3]  = p[3]  ^ c[3];

    assign sum[4]  = p[4]  ^ c[4];
    assign sum[5]  = p[5]  ^ c[5];
    assign sum[6]  = p[6]  ^ c[6];
    assign sum[7]  = p[7]  ^ c[7];

    assign sum[8]  = p[8]  ^ c[8];
    assign sum[9]  = p[9]  ^ c[9];
    assign sum[10] = p[10] ^ c[10];
    assign sum[11] = p[11] ^ c[11];

    assign sum[12] = p[12] ^ c[12];
    assign sum[13] = p[13] ^ c[13];
    assign sum[14] = p[14] ^ c[14];
    assign sum[15] = p[15] ^ c[15];

    assign sum[16] = p[16] ^ c[16];
    assign sum[17] = p[17] ^ c[17];
    assign sum[18] = p[18] ^ c[18];
    assign sum[19] = p[19] ^ c[19];

    assign sum[20] = p[20] ^ c[20];
    assign sum[21] = p[21] ^ c[21];
    assign sum[22] = p[22] ^ c[22];
    assign sum[23] = p[23] ^ c[23];

    assign sum[24] = p[24] ^ c[24];
    assign sum[25] = p[25] ^ c[25];
    assign sum[26] = p[26] ^ c[26];
    assign sum[27] = p[27] ^ c[27];

    assign sum[28] = p[28] ^ c[28];
    assign sum[29] = p[29] ^ c[29];
    assign sum[30] = p[30] ^ c[30];
    assign sum[31] = p[31] ^ c[31];

    /*==========================================================
     * Carry Out
     *==========================================================*/

    assign cout = c[32];

endmodule
