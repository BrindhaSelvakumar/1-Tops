
module execute_stage_cover(

    input logic clk,
    input logic rst_n,

    input logic [31:0] ex_pc,
    input logic [31:0] rdata1,
    input logic [31:0] rdata2,
    input logic [31:0] imm,

    input logic [2:0] funct3,
    input logic [4:0] alu_ctrl,

    input logic [1:0] op1_src,
    input logic alu_src_ctrl,
    input logic m_ext_ctrl,
    input logic jump_ctrl,
    input logic branch_ctrl,

    input logic [31:0] mem_alu_result,
    input logic [31:0] wb_data,

    input logic [1:0] forward_a,
    input logic [1:0] forward_b,

    input logic [31:0] final_result,
    input logic [31:0] branch_target,
    input logic [31:0] jump_target,

    input logic branch_taken,
    input logic m_unit_busy,

    input logic [31:0] fwd_rs2_out

);

//////////////////////////////////////////////////////
// Cover 1 : Forward A from MEM
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
forward_a==2'b10);

//////////////////////////////////////////////////////
// Cover 2 : Forward A from WB
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
forward_a==2'b01);

//////////////////////////////////////////////////////
// Cover 3 : Forward A from Register
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
forward_a==2'b00);

//////////////////////////////////////////////////////
// Cover 4 : Forward B from MEM
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
forward_b==2'b10);

//////////////////////////////////////////////////////
// Cover 5 : Forward B from WB
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
forward_b==2'b01);

//////////////////////////////////////////////////////
// Cover 6 : Forward B from Register
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
forward_b==2'b00);

//////////////////////////////////////////////////////
// Cover 7 : Branch Instruction
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
branch_ctrl);

//////////////////////////////////////////////////////
// Cover 8 : Branch Taken
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
branch_taken);

//////////////////////////////////////////////////////
// Cover 9 : Jump Instruction
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
jump_ctrl);

//////////////////////////////////////////////////////
// Cover 10 : M Extension Instruction
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
m_ext_ctrl);

//////////////////////////////////////////////////////
// Cover 11 : Busy State
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
m_unit_busy);

//////////////////////////////////////////////////////
// Cover 12 : Immediate Operand Selected
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
alu_src_ctrl);

//////////////////////////////////////////////////////
// Cover 13 : Register Operand Selected
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
!alu_src_ctrl);

//////////////////////////////////////////////////////
// Cover 14 : Operand A = Register
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
op1_src==2'b00);

//////////////////////////////////////////////////////
// Cover 15 : Operand A = PC
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
op1_src==2'b01);

//////////////////////////////////////////////////////
// Cover 16 : Operand A = ZERO
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
op1_src==2'b10);

//////////////////////////////////////////////////////
// Cover 17 : BEQ Instruction
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
branch_ctrl && funct3==3'b000);

//////////////////////////////////////////////////////
// Cover 18 : BNE Instruction
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
branch_ctrl && funct3==3'b001);

//////////////////////////////////////////////////////
// Cover 19 : JALR Instruction
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
jump_ctrl && funct3==3'b000);

//////////////////////////////////////////////////////
// Cover 20 : JAL Instruction
//////////////////////////////////////////////////////

cover property (@(posedge clk) disable iff(!rst_n)
jump_ctrl && funct3!=3'b000);

endmodule
